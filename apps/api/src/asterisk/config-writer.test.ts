import { beforeEach, describe, expect, it, vi } from "vitest";
import { mkdirSync, readFileSync } from "node:fs";

// Pin every filesystem/AMI touchpoint BEFORE config.js is imported (it reads
// env at module init). CLI reload is disabled so the run stays hermetic and
// the reload.flag lands inside the temp config dir.
vi.hoisted(() => {
  const base = `${process.env.TMPDIR ?? "/tmp"}/monosip-cw-emergency-test`;
  process.env.ASTERISK_CONFIG_DIR = base;
  process.env.RECORDINGS_DIR = `${base}/recordings`;
  process.env.UPLOADS_DIR = `${base}/uploads`;
  process.env.ASTERISK_AMI_PORT = "1"; // connect refused immediately, caught by astdb-dnd
  process.env.MONOSIP_ASTERISK_CLI_RELOAD = "0";
  process.env.MONOSIP_SIP_GUARD = "0";
});

// The config writer's DB reads are the boundary here; every table resolves to
// an empty result set — the emergency dialplan block is data-independent.
vi.mock("../db/client.js", () => {
  const rows: unknown[] = [];
  const chain: Record<string, unknown> = {
    from: () => chain,
    innerJoin: () => chain,
    leftJoin: () => chain,
    where: () => chain,
    orderBy: () => chain,
    limit: () => chain,
    offset: () => chain,
    set: () => chain,
    values: () => chain,
    returning: async () => [],
    onConflictDoNothing: () => chain,
    then: (res: (v: unknown[]) => void, rej?: (e: unknown) => void) =>
      Promise.resolve(rows).then(res, rej),
  };
  return {
    db: {
      select: () => chain,
      insert: () => chain,
      update: () => chain,
      delete: () => chain,
    },
    pool: {},
  };
});

import { holdMusicSuggest, queueSelfPauseLines, queueSelfUnpauseLines, writeAsteriskConfig } from "./config-writer.js";

// Must match the authoritative policy set in lib/call-policy.ts (EMERGENCY).
// The generated [from-internal] emergency shortcuts exist so these numbers
// dial WITHOUT the monosip-blacklist Gosub that the _X. catch-all runs —
// emergency access must never depend on the blacklist.
const POLICY_EMERGENCY = ["112", "911", "155", "110", "119"];

describe("holdMusicSuggest", () => {
  const classes = [{ name: "lobby" }, { name: "default" }];

  it("uses a class that exists on the hold-music page", () => {
    expect(holdMusicSuggest("lobby", classes)).toBe("lobby");
  });

  it("falls back to the built-in tone when nothing is chosen", () => {
    expect(holdMusicSuggest("", classes)).toBe("default");
    expect(holdMusicSuggest(null, classes)).toBe("default");
    expect(holdMusicSuggest("missing", classes)).toBe("default");
  });
});

describe("writeAsteriskConfig emergency dialplan", () => {
  let dialplan: string;

  beforeEach(async () => {
    mkdirSync(`${process.env.TMPDIR ?? "/tmp"}/monosip-cw-emergency-test`, { recursive: true });
    await writeAsteriskConfig();
    dialplan = readFileSync(
      `${process.env.TMPDIR ?? "/tmp"}/monosip-cw-emergency-test/extensions_monosip.conf`,
      "utf8",
    );
  });

  it("wrote a non-empty dialplan", () => {
    expect(dialplan.length).toBeGreaterThan(100);
    expect(dialplan).toContain("Auto-generated by MonoSIP");
  });

  it.each(POLICY_EMERGENCY)("routes emergency number %s without the blacklist", (em) => {
    const block = `exten => ${em},1,NoOp(Emergency ${em})`;
    expect(
      dialplan,
      `emergency ${em} must be routed directly (no blacklist) like the rest of the policy set`,
    ).toContain(block);
    const start = dialplan.indexOf(block);
    const section = dialplan.slice(start, dialplan.indexOf("\n\n", start));
    expect(section, `emergency ${em} must not run the blacklist Gosub`).not.toContain(
      "monosip-blacklist",
    );
  });

  it("keeps the catch-all for everything else (control)", () => {
    expect(dialplan).toContain("exten => _X.,1,NoOp(Outbound ${EXTEN})");
  });

  it("reads PJSIP RTCP stats, not the chan_sip rtpqos items", () => {
    expect(dialplan).toContain("CHANNEL(rtcp,txmes)");
    expect(dialplan).toContain("CHANNEL(rtcp,rxjitter)");
    expect(dialplan).toContain("CHANNEL(rtcp,rxploss)");
    expect(dialplan).not.toContain("rtpqos");
  });

  it("unpauses on hangup only when this call paused a member", () => {
    const start = dialplan.indexOf("same => n(hqueue)");
    const section = dialplan.slice(start, dialplan.indexOf("same => n(cdrdone)", start));
    expect(section).toContain('GotoIf($["${MONOSIP_QPAUSED}" != "1"]?hunpaused)');
    expect(section.indexOf("MONOSIP_QPAUSED")).toBeLessThan(section.indexOf("UnpauseQueueMember"));
  });
});

describe("queue self pause", () => {
  it("pauses PJSIP/<caller> only when that interface is in the member list", () => {
    const lines = queueSelfPauseLines("300").join("\n");
    expect(lines).toContain("QUEUE_MEMBER_LIST(300)");
    expect(lines).toContain(',PJSIP/${CALLERID(num)},');
    expect(lines.indexOf("GotoIf")).toBeLessThan(lines.indexOf("PauseQueueMember"));
    expect(lines).toContain("Set(MONOSIP_QPAUSED=1)");
  });

  it("skips unpause unless the pause flag is set", () => {
    const lines = queueSelfUnpauseLines("300", "qunpaused").join("\n");
    expect(lines.indexOf('"${MONOSIP_QPAUSED}" != "1"')).toBeLessThan(
      lines.indexOf("UnpauseQueueMember"),
    );
    expect(lines).toContain("same => n(qunpaused),NoOp(Queue self-unpause)");
  });
});
